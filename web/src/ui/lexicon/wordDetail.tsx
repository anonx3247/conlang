function flatten(node: AncestryNode): AncestryNode[][] {
  const byDepth = new Map<number, AncestryNode[]>();
  const seen = new Set<Id>();
  const walk = (nodes: AncestryNode[], depth: number) => {
    for (const n of nodes) {
      if (seen.has(n.lexemeId)) continue;
      seen.add(n.lexemeId);
      byDepth.set(depth, [...(byDepth.get(depth) ?? []), n]);
      walk(n.parents, depth + 1);
    }
  };
  walk(node.parents, 1);
  const max = Math.max(0, ...byDepth.keys());
  const out: AncestryNode[][] = [];
  for (let d = max; d >= 1; d--) out.push(byDepth.get(d) ?? []);
  return out;
}

function Connector({ count, inverted }: { count: number; inverted?: boolean }) {
  const w = 240;
  const h = 18;
  const cx = w / 2;
  const stroke = 'var(--outline-variant)';
  if (count <= 1) return <svg width={w} height={h} aria-hidden style={{ display: 'block', margin: '0 auto' }}><line x1={cx} y1={0} x2={cx} y2={h} stroke={stroke} /></svg>;
  const spread = count === 2 ? 0.3 : 0.45;
  const left = w * (0.5 - spread);
  const right = w * (0.5 + spread);
  const bar = inverted ? h * 0.6 : h * 0.4;
  const stems = count >= 3 ? [left, cx, right] : [left, right];
  return (
    <svg width={w} height={h} aria-hidden style={{ display: 'block', margin: '0 auto' }}>
      {stems.map((x) => <line key={x} x1={x} y1={inverted ? bar : 0} x2={x} y2={inverted ? h : bar} stroke={stroke} />)}
      <line x1={left} y1={bar} x2={right} y2={bar} stroke={stroke} />
      <line x1={cx} y1={inverted ? 0 : bar} x2={cx} y2={inverted ? bar : h} stroke={stroke} />
    </svg>
  );
}

function Pill({ id, edge, onNavigate, current }: { id: Id; edge?: string; onNavigate?: (id: Id) => void; current?: boolean }) {
  const engine = useEngine();
  const l = engine.lexeme(id);
  const f = engine.form(id);
  const inner = (
    <>
      <span className="bold small" data-testid="pill-form">{f.label}</span>
      {l && engine.glossOf(l) && <span className="tiny faint" style={current ? { color: 'inherit', opacity: 0.8 } : undefined}>{engine.glossOf(l)}</span>}
    </>
  );
  return (
    <span className="tier">
      {onNavigate ? <button type="button" className="pill" onClick={() => onNavigate(id)}>{inner}</button> : <span className={`pill ${current ? 'current' : ''}`}>{inner}</span>}
      {edge && <span className="tiny faint">{edge}</span>}
    </span>
  );
}

function EtymologyChain({ lexeme: l, onNavigate }: { lexeme: Lexeme; onNavigate: (id: Id) => void }) {
  const engine = useEngine();
  const [adding, setAdding] = useState(false);
  const node = engine.ancestry(l.id);
  const levels = node ? flatten(node) : [];
  const children = engine.childrenOf(l.id);
  const manual = engine.doc.parents.filter((p) => p.childId === l.id).map((p) => p.parentId);
  return (
    <div className="col" style={{ gap: 2 }} data-testid="etymology">
      {(levels.length > 0 || children.length > 0) && <div className="bold">Etymology Chain</div>}
      {levels.map((level, i) => (
        <div key={i}>
          <div className="row wrap" style={{ justifyContent: 'center', gap: 6 }}>
            {level.map((n) =>
              n.isTruncated ? <span key={n.lexemeId} className="tiny faint">↑ more ancestors</span>
              : n.isCycle ? <Chip key={n.lexemeId}><Icon name="warning" size={12} /> cycle</Chip>
              : <Pill key={n.lexemeId} id={n.lexemeId} edge={n.edgeLabel} onNavigate={onNavigate} />,
            )}
          </div>
          <Connector count={level.length} />
        </div>
      ))}
      {(levels.length > 0 || children.length > 0) && (
        <div className="row" style={{ justifyContent: 'center' }}><Pill id={l.id} current /></div>
      )}
      {children.length > 0 && (
        <>
          <Connector count={children.length} inverted />
          <div className="row wrap" style={{ justifyContent: 'center', gap: 6 }}>
            {children.map((c, i) => <Pill key={`${c.lexeme.id}-${i}`} id={c.lexeme.id} edge={c.edgeLabel} onNavigate={onNavigate} />)}
          </div>
        </>
      )}
      {adding ? (
        <div className="col" style={{ marginTop: 6 }}>
          <ParentSelector selected={manual} excludeId={l.id} onChange={(ids) => run((d) => cmd.setParents(d, l.id, ids))} />
          <div><TextButton onClick={() => setAdding(false)}>Done</TextButton></div>
        </div>
      ) : (
        <div className="row" style={{ justifyContent: levels.length || children.length ? 'center' : 'flex-start' }}><TextButton icon="add" onClick={() => setAdding(true)}>Add parent</TextButton></div>
      )}
    </div>
  );
}

