function DerivationTree({ lexeme: l, onNavigate }: { lexeme: Lexeme; onNavigate: (id: Id) => void }) {
  const engine = useEngine();
  const options = engine.derivationOptions(l.id);
  const f = engine.form(l.id);
  return (
    <div className="col" style={{ gap: 4 }} data-testid="derivations">
      <div className="row">
        <span className="bold">Derivations</span>
        <span className="badge">{options.length} derived form{options.length === 1 ? '' : 's'}</span>
      </div>
      {options.length === 0 ? (
        <div className="small faint">No derivations. Add morphological rules to see derived forms.</div>
      ) : (
        <>
          <div className="small muted">{f.label} {f.label !== f.phonetic && <span className="ipa">[{f.phonetic}]</span>}</div>
          {options.map((o) => <DerivedRow key={o.rule.id} parentId={l.id} option={o} onNavigate={onNavigate} />)}
        </>
      )}
    </div>
  );
}

function DerivedRow({ parentId, option: o, onNavigate }: { parentId: Id; option: DerivationOption; onNavigate: (id: Id) => void }) {
  const engine = useEngine();
  const [meaning, setMeaning] = useState(o.child?.meaning ?? '');
  useEffect(() => setMeaning(o.child?.meaning ?? ''), [o.child?.meaning]);
  const pos = engine.pos(o.rule.outputPosId);

  const automatic = !!o.rule.autoApply && !!o.child;

  const submitMeaning = async () => {
    const trimmed = meaning.trim();
    if (automatic) {
      if (trimmed !== (o.child!.meaning ?? '')) run((d) => cmd.updateWord(d, o.child!.id, { meaning: trimmed }));
      return;
    }
    if (!o.child && trimmed) {
      run((d) => cmd.promoteDerivation(d, parentId, o.rule.id, trimmed));
    } else if (o.child && !trimmed) {
      const ok = await confirmDialog({ title: 'Remove derivation?', body: <>Remove this derivation from the dictionary? The row can be re-promoted later by typing a meaning into the field again.<SlotUseWarning id={o.child.id} /></>, confirm: 'Remove', danger: false });
      if (ok) run((d) => cmd.demoteDerivation(d, o.child!.id));
      else setMeaning(o.child.meaning ?? '');
    } else if (o.child && trimmed !== (o.child.meaning ?? '')) {
      run((d) => cmd.updateWord(d, o.child!.id, { meaning: trimmed }));
    }
  };

  const editForm = async () => {
    if (!o.child) {
      snack('Add a meaning first to promote this derivation before editing its form.');
      return;
    }
    const child = o.child;
    if (automatic) {
      const result = await openDialog<{ ipa: string; rom: string }>((close) => <FormEditDialog ipa={o.phonemic} rom={o.roman} close={close} />);
      if (result) run((d) => cmd.updateWord(d, child.id, { phonemic: result.ipa }));
      return;
    }
    const ok = await confirmDialog({ title: 'Unlink from rule?', body: `Editing this form will unlink it from rule "${o.rule.name}". The row will become standalone — future edits to the rule will no longer update this form. Continue?`, confirm: 'Unlink and edit', danger: false });
    if (!ok) return;
    const result = await openDialog<{ ipa: string; rom: string }>((close) => <FormEditDialog ipa={o.phonemic} rom={o.roman} close={close} />);
    if (result) run((d) => cmd.detachWord(d, child.id, result.ipa, result.rom || null));
  };

  return (
    <div className="row" style={{ paddingLeft: 12 }} data-testid={`derived-${o.rule.name}`}>
      <span style={{ width: 14, borderTop: '1px solid var(--outline-variant)' }} />
      {pos && <span className="badge">{formatAbbr(pos.abbr)}</span>}
      <div style={{ minWidth: 0, flexShrink: 1 }}>
        <div className="row" style={{ gap: 6 }}>
          {o.child ? (
            <button type="button" className={o.isException ? 'amber bold' : 'primary'} style={{ textDecoration: 'underline' }} onClick={() => onNavigate(o.child!.id)} data-testid="derived-form">
              {o.label} <Icon name="open_in_new" size={12} />
            </button>
          ) : (
            <span className={o.isException ? 'amber bold' : ''} data-testid="derived-form">{o.label}</span>
          )}
          <span className="small faint">{o.rule.name}</span>
          {o.isException && <span className="badge amber">Exception</span>}
        </div>
        {o.label !== o.phonetic && <div className="small ipa">[{o.phonetic}]</div>}
      </div>
      <span className="grow" />
      {automatic && <span className="badge tertiary" title="Generated by this rule, not stored">auto</span>}
      {o.child && <span title={`linked to rule "${o.rule.name}"`}><Icon name="link" size={14} className="primary" /></span>}
      <div style={{ width: 170, flex: 'none' }}>
        {o.child && isParticle(o.child) ? <span className="chip">{o.child.glossTag}</span> : <input type="text" placeholder={automatic ? 'Meaning' : 'Add meaning to save…'} aria-label={`Meaning for ${o.label}`} value={meaning} onChange={(e) => setMeaning(e.target.value)} onBlur={() => void submitMeaning()} onKeyDown={(e) => { if (e.key === 'Enter') e.currentTarget.blur(); }} />}
      </div>
      <IconButton icon="edit" size={14} title="Edit form" onClick={() => void editForm()} />
    </div>
  );
}

function FormEditDialog({ ipa, rom, close }: { ipa: string; rom: string; close: (v?: { ipa: string; rom: string }) => void }) {
  const [i, setI] = useState(ipa);
  const [r, setR] = useState(rom);
  return (
    <Dialog title="Edit derived form" onClose={() => close()} actions={<><TextButton onClick={() => close()}>Cancel</TextButton><FilledButton disabled={!i.trim()} onClick={() => close({ ipa: i.trim(), rom: r.trim() })}>Save</FilledButton></>}>
      <IpaField autoFocus label="IPA" value={i} onChange={setI} />
      <TextField label="Romanization" value={r} onChange={setR} />
    </Dialog>
  );
}

function Suggestions({ lexeme: l }: { lexeme: Lexeme }) {
  const engine = useEngine();
  const list = engine.derivationSuggestions(l.id);
  if (!list.length) return null;
  return (
    <div className="col" style={{ gap: 4 }} data-testid="suggestions">
      <div className="bold">Suggestions</div>
      <div className="row wrap" style={{ gap: 6 }}>
        {list.map((o) => (
          <Chip key={o.rule.id} title={`Add ${o.label} to the dictionary`} onClick={() => run((d) => cmd.promoteDerivation(d, l.id, o.rule.id, ''))}>{o.rule.name}: {o.label}</Chip>
        ))}
      </div>
    </div>
  );
}

