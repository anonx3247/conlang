export function WordDetailPanel({ lexemeId, onDeleted, onNavigate }: { lexemeId: Id; onDeleted: () => void; onNavigate: (id: Id) => void }) {
  const [editing, setEditing] = useState(false);
  const engine = useEngine();
  const l = engine.lexeme(lexemeId);
  if (!l) return <div className="center faint">Word not found.</div>;
  return editing ? <EditMode lexeme={l} onDone={() => setEditing(false)} /> : <ViewMode lexeme={l} onEdit={() => setEditing(true)} onDeleted={onDeleted} onNavigate={onNavigate} />;
}

function ViewMode({ lexeme: l, onEdit, onDeleted, onNavigate }: { lexeme: Lexeme; onEdit: () => void; onDeleted: () => void; onNavigate: (id: Id) => void }) {
  const engine = useEngine();
  const f = engine.form(l.id);
  const violations = engine.wordViolations(l.id);
  const pos = engine.pos(l.posId);
  const automatic = engine.isDynamic(l);
  const remove = async () => {
    const childCount = engine.childrenOf(l.id).filter((c) => c.isRuleDerived).length;
    const ok = await confirmDialog({
      title: 'Delete word?',
      body: (
        <>
          Delete "{f.label}"?{childCount ? ` ${childCount} word(s) derived from it will keep their current forms as standalone words.` : ''} This cannot be undone.
          <SlotUseWarning id={l.id} />
        </>
      ),
    });
    if (ok) {
      run((d) => cmd.deleteWord(d, l.id));
      onDeleted();
    }
  };
  const levelNames = pos
    ? engine.dimensionsForPos(pos.id).filter((d) => d.intrinsic).flatMap((d) => {
        const id = engine.intrinsicLevels(l)[d.id];
        const name = d.levels.find((x) => x.id === id)?.name;
        return name ? [name] : [];
      })
    : [];
  return (
    <div className="col pad-lg" style={{ gap: 12 }} data-testid="word-detail">
      <div className="row top">
        <div className="grow">
          {f.status === 'broken' ? (
            <div className="banner error" data-testid="broken-form"><Icon name="error_outline" size={16} /><span>{f.reason}</span></div>
          ) : (
            <>
              <h1 className={`h-large ${f.ipaOverridden ? 'overridden' : ''}`} data-testid="word-form">{f.label}</h1>
              <div className={f.ipaOverridden ? 'overridden' : 'muted'} data-testid="word-phonetic">
                [<ViolationText text={f.phonetic} violations={l.isException ? [] : violations} />]
                {f.phonetic !== f.phonemic && <span className="faint small"> /{f.phonemic}/</span>}
              </div>
            </>
          )}
          {f.origin !== 'root' && f.chain.length > 0 && (
            <div className="small faint" data-testid="derived-via">Derived via {f.chain.map((c) => c.rule.name).join(' → ')}</div>
          )}
          {automatic && <div className="small faint" data-testid="automatic-note">Generated by an automatic rule, so it follows the rule. Your edits are saved on top of it.</div>}
          {f.origin === 'detached' && <div className="small faint">Hand-edited: no longer follows its rule.</div>}
          {l.isException ? (
            <div className="row small amber" style={{ marginTop: 4 }}>
              <Icon name="warning_amber" size={14} /> Phonotactic exception
              <TextButton onClick={() => run((d) => cmd.setWordException(d, l.id, false))}>Remove exception</TextButton>
            </div>
          ) : violations.length > 0 ? (
            <div style={{ marginTop: 4 }}><TextButton icon="warning_amber" onClick={() => run((d) => cmd.setWordException(d, l.id, true))}>Mark as exception</TextButton></div>
          ) : null}
        </div>
        <IconButton icon="edit" title="Edit word" onClick={onEdit} />
        {!automatic && <IconButton icon="delete_outline" title="Delete word" onClick={() => void remove()} />}
      </div>
      {isParticle(l) ? <div data-testid="word-tag"><span className="chip">{l.glossTag}</span></div> : l.meaning && <div style={{ fontSize: 15 }}>{l.meaning}</div>}
      {pos && <div><Chip>{pos.name}{levelNames.length ? ` (${levelNames.join(', ')})` : ''}</Chip></div>}
      <EtymologyChain lexeme={l} onNavigate={onNavigate} />
      <DerivationTree lexeme={l} onNavigate={onNavigate} />
      <Suggestions lexeme={l} />
      {pos && engine.dimensionsForPos(pos.id).length > 0 && (
        <div className="card" data-testid="word-paradigm">
          <div className="bold" style={{ marginBottom: 8 }}>Paradigm</div>
          <ParadigmTable lexemeId={l.id} posId={pos.id} mode="wordOverride" />
          <SkippedDimensions lexeme={l} />
        </div>
      )}
      <WordConstructions lexeme={l} />
      <Exceptions lexeme={l} />
      {automatic ? (
        <div><TextButton onClick={() => run((d) => cmd.resetAutomaticWord(d, l.id))}>Reset to rule output</TextButton></div>
      ) : (
        <div><TextButton danger onClick={() => void remove()}>Delete</TextButton></div>
      )}
    </div>
  );
}

/** Says which constructions lose a word when it is deleted. */
function SlotUseWarning({ id }: { id: Id }) {
  const engine = useEngine();
  const used = cmd.constructionsUsingWord(engine.doc, id);
  if (!used.length) return null;
  return (
    <div className="col amber" style={{ gap: 2, marginTop: 8 }} data-testid="slot-use-warning">
      <div>It is used in these constructions, where its slot will be marked missing:</div>
      {used.map((c) => <div key={c.id}>• {c.name}</div>)}
    </div>
  );
}

function SkippedDimensions({ lexeme: l }: { lexeme: Lexeme }) {
  const engine = useEngine();
  const dims = engine.dimensionsForPos(l.posId!).filter((d) => !d.intrinsic);
  if (!dims.length) return null;
  return (
    <div className="row wrap small" style={{ marginTop: 8, gap: 6 }}>
      <span className="faint">Inflects for:</span>
      {dims.map((d) => {
        const on = !l.skippedDimensionIds.includes(d.id);
        return (
          <Chip key={d.id} selected={on} title={`Whether this word varies by ${d.name}`} onClick={() => run((doc) => cmd.setSkippedDimension(doc, l.id, d.id, on))}>{d.name}</Chip>
        );
      })}
    </div>
  );
}

function WordConstructions({ lexeme: l }: { lexeme: Lexeme }) {
  const engine = useEngine();
  const list = engine.constructionsForWord(l);
  if (!list.length) return null;
  return (
    <div className="col" style={{ gap: 4 }} data-testid="word-constructions">
      <div className="bold">Constructions</div>
      {list.map((c) => (
        <div key={c.id} className="row small">
          <span className="muted" style={{ width: 140, flex: 'none' }}>{c.name}</span>
          <span>{engine.fillConstruction(c, l).map((p, i) => <span key={i} className={p.missing ? 'err' : p.isTargetWord ? 'bold' : ''}>{i > 0 ? ' ' : ''}{p.text}{p.tag && p.isTargetWord && <span className="badge" style={{ marginLeft: 4 }}>{p.tag}</span>}</span>)}</span>
        </div>
      ))}
    </div>
  );
}

