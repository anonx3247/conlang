function EditMode({ lexeme: l, onDone }: { lexeme: Lexeme; onDone: () => void }) {
  const engine = useEngine();
  const f = engine.form(l.id);
  const fields = useWordFields({ rom: f.roman, ipa: f.phonemic, manual: f.ipaOverridden });
  const [meaning, setMeaning] = useState(l.meaning ?? '');
  const [particle, setParticle] = useState(isParticle(l));
  const [tag, setTag] = useState(l.glossTag ?? '');
  const [tagError, setTagError] = useState<string | null>(null);
  const [posId, setPosId] = useState(l.posId);
  const [levels, setLevels] = useState<Record<string, Id>>(engine.intrinsicLevels(l));
  const [posError, setPosError] = useState<string | null>(null);
  const [errors, setErrors] = useState<Record<string, string>>({});
  const automatic = engine.isDynamic(l);
  const linked = f.origin === 'derived' && !automatic;

  const save = async () => {
    const ipa = fields.ipa.trim();
    if (!ipa) return;
    if (particle && !tag.trim()) {
      setTagError('A gloss tag is required');
      return;
    }
    if (!l.rootOnly && posId === null && !particle) {
      setPosError('Part of speech is required');
      return;
    }
    const missing: Record<string, string> = {};
    if (posId !== null && !particle && !automatic) {
      for (const d of engine.dimensionsForPos(posId).filter((x) => x.intrinsic)) {
        if (levels[d.id] === undefined) missing[d.id] = `Required — every ${engine.pos(posId)?.name} must have a fixed ${d.name}.`;
      }
    }
    setErrors(missing);
    if (Object.keys(missing).length) return;
    const formChanged = ipa !== f.phonemic || (fields.rom.trim() !== f.roman && !!fields.rom.trim());
    if (linked && formChanged) {
      const rule = f.chain[f.chain.length - 1]?.rule.name;
      const ok = await confirmDialog({ title: 'Unlink from rule?', body: `Editing this form will unlink it from rule "${rule}". The row will become standalone — future edits to the rule will no longer update this form. Continue?`, confirm: 'Unlink and edit', danger: false });
      if (!ok) return;
    }
    const posDims = posId !== null ? engine.dimensionsForPos(posId) : [];
    const kept = Object.fromEntries(Object.entries(levels).filter(([d]) => posDims.some((x) => x.id === Number(d) && x.intrinsic)));
    run((d) => cmd.updateWord(d, l.id, { phonemic: ipa, roman: fields.rom, meaning: particle ? null : meaning, ...(automatic ? {} : { glossTag: particle ? tag : null }), posId, intrinsicLevels: kept }));
    onDone();
  };

  return (
    <div className="col pad-lg" style={{ gap: 14, maxWidth: 620 }}>
      <h1 className="h-large">Edit word</h1>
      <WordFormFields fields={fields} />
      {!automatic && <WordKindSwitch particle={particle} onChange={setParticle} />}
      {particle ? (
        <GlossTagInput value={tag} onChange={(v) => { setTag(v); setTagError(null); }} error={tagError} warning={sharedTagWarning(engine, tag, l.id)} />
      ) : (
        <TextField label="Meaning" value={meaning} onChange={setMeaning} />
      )}
      {!automatic && engine.doc.partsOfSpeech.length > 0 && (
        <SelectField label={particle ? 'Part of speech' : 'Part of speech *'} value={posId} placeholder={particle ? 'Particle' : '— none —'} error={posError} options={engine.doc.partsOfSpeech.map((p) => ({ value: p.id, label: p.name }))} onChange={(v) => { setPosId(v); setPosError(null); setErrors({}); }} />
      )}
      <IntrinsicFields posId={posId} values={levels} errors={errors} onChange={(dim, level) => { const next = { ...levels }; if (level === null) delete next[dim]; else next[dim] = level; setLevels(next); }} />
      <div className="row">
        <FilledButton onClick={() => void save()}>Save</FilledButton>
        <TextButton onClick={onDone}>Cancel</TextButton>
      </div>
    </div>
  );
}


