function Exceptions({ lexeme: l }: { lexeme: Lexeme }) {
  const engine = useEngine();
  const rows = engine.doc.exceptions.filter((e) => e.lexemeId === l.id);
  const add = () => {
    if (!engine.doc.rules.length) {
      snack('No morphological rules defined yet.');
      return;
    }
    void openDialog<void>((close) => <ExceptionDialog lexemeId={l.id} close={() => close()} />);
  };
  return (
    <div className="col" style={{ gap: 4 }} data-testid="exceptions">
      <div className="row between">
        <span className="bold">Exceptions</span>
        <TextButton icon="add" onClick={add}>Add exception</TextButton>
      </div>
      {rows.length === 0 ? (
        <div className="small faint">No exceptions. This word follows all active rules.</div>
      ) : (
        rows.map((e) => (
          <div key={e.id} className="row">
            <div className="grow">
              <div>{e.form}</div>
              <div className="small faint">via {engine.rule(e.ruleId)?.name ?? `Rule #${e.ruleId}`}</div>
            </div>
            <IconButton
              icon="close"
              size={16}
              title="Remove exception"
              onClick={() => void confirmDialog({ title: 'Remove exception?', body: 'Remove this exception? The rule will apply to this word again.', confirm: 'Remove' }).then((ok) => { if (ok) run((d) => cmd.deleteException(d, e.id)); })}
            />
          </div>
        ))
      )}
    </div>
  );
}

function ExceptionDialog({ lexemeId, close }: { lexemeId: Id; close: () => void }) {
  const engine = useEngine();
  const [ruleId, setRuleId] = useState<Id | null>(engine.doc.rules[0]?.id ?? null);
  const [form, setForm] = useState('');
  return (
    <Dialog
      title="Add exception"
      onClose={close}
      actions={
        <>
          <TextButton onClick={close}>Cancel</TextButton>
          <FilledButton disabled={!form.trim() || ruleId === null} onClick={() => { mutate((d) => cmd.addException(d, lexemeId, ruleId!, form)); close(); }}>Save</FilledButton>
        </>
      }
    >
      <SelectField label="Rule" value={ruleId} options={engine.doc.rules.map((r) => ({ value: r.id, label: r.name }))} onChange={setRuleId} />
      <IpaField autoFocus label="Override form" placeholder="Irregular form (IPA)" value={form} onChange={setForm} />
    </Dialog>
  );
}

