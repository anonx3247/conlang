// How a word is displayed. Every screen uses these, and they get forms only
// from the engine, so a word looks the same wherever it appears.

import { useMemo, useState } from 'react';
import type { WordForm } from '../core/engine';
import type { Violation } from '../core/phonology';
import type { Id, Lexeme } from '../core/types';
import leipzig from '../data/leipzig.json';
import { useEngine } from '../storage/store';
import { Chip, Icon, TextField, ViolationText } from './common';

export function WordLabel({ id, className }: { id: Id; className?: string }) {
  const engine = useEngine();
  const f = engine.form(id);
  return <span className={`${className ?? ''} ${f.status === 'broken' ? 'err' : f.ipaOverridden ? 'overridden' : ''}`} title={f.reason}>{f.label}</span>;
}

/** The surface form in brackets, with violations marked. */
export function Phonetic({ form, violations }: { form: WordForm; violations?: Violation[] }) {
  if (form.status === 'broken') return <span className="err small">{form.reason}</span>;
  return (
    <span className="ipa small">
      [<ViolationText text={form.phonetic} violations={violations ?? []} />]
    </span>
  );
}

/** Romanized first with the phonetic form beneath: the app's standard word layout. */
export function StackedForm({ roman, phonetic, showRoman }: { roman: string; phonetic: string; showRoman: boolean }) {
  return showRoman ? (
    <div className="col" style={{ gap: 0 }}>
      <span>{roman}</span>
      <span className="ipa small">[{phonetic}]</span>
    </div>
  ) : (
    <span>[{phonetic}]</span>
  );
}

export function wordOption(engine: ReturnType<typeof useEngine>, l: Lexeme) {
  const f = engine.form(l.id);
  const gloss = engine.glossOf(l);
  return gloss ? `${f.label} — ${gloss}` : f.label;
}

export function GlossTagInput({ label, value, onChange, autoFocus, error, warning }: { label?: string; value: string; onChange: (v: string) => void; autoFocus?: boolean; error?: string | null; warning?: string | null }) {
  return (
    <>
      <TextField autoFocus={autoFocus} label={label ?? 'Gloss tag'} placeholder="e.g. NEG, DEF, PROG" maxLength={20} list="leipzig-tags" value={value} onChange={onChange} error={error} help={warning && <span className="amber" data-testid="tag-warning">{warning}</span>} />
      <datalist id="leipzig-tags">{leipzig.map((l) => <option key={l.abbreviation} value={l.abbreviation}>{l.meaning}</option>)}</datalist>
    </>
  );
}

/** Searches every word, including ones generated by automatic rules. */
export function WordPicker({ label, onPick, autoFocus }: { label: string; onPick: (id: Id) => void; autoFocus?: boolean }) {
  const engine = useEngine();
  const [query, setQuery] = useState('');
  const q = query.toLowerCase();
  const options = useMemo(() => {
    if (!q) return [];
    return engine.allWords()
      .map((l) => engine.lexeme(l.id)!)
      .filter((l) => {
        const f = engine.form(l.id);
        return f.roman.toLowerCase().includes(q) || f.phonemic.toLowerCase().includes(q) || engine.glossOf(l).toLowerCase().includes(q);
      })
      .slice(0, 20);
  }, [engine, q]);
  return (
    <div style={{ position: 'relative' }}>
      <input type="text" autoFocus={autoFocus} value={query} onChange={(e) => setQuery(e.target.value)} placeholder="Type a form or meaning…" aria-label={label} />
      {options.length > 0 && (
        <div className="menu" style={{ position: 'absolute', left: 0, right: 0, top: '100%', maxHeight: 220, overflow: 'auto' }}>
          {options.map((l) => (
            <button key={l.id} type="button" className="menu-item" onClick={() => onPick(l.id)}>{wordOption(engine, l)}</button>
          ))}
        </div>
      )}
    </div>
  );
}

/** Whether a word holds a meaning or is gloss-only. */
export function WordKindSwitch({ particle, onChange }: { particle: boolean; onChange: (particle: boolean) => void }) {
  return (
    <div className="row" role="radiogroup" aria-label="Word type">
      <button type="button" role="radio" aria-checked={!particle} className={`chip ${particle ? '' : 'sel'}`} onClick={() => onChange(false)}>{!particle && <Icon name="check" size={14} />}Meaning</button>
      <button type="button" role="radio" aria-checked={particle} className={`chip ${particle ? 'sel' : ''}`} onClick={() => onChange(true)}>{particle && <Icon name="check" size={14} />}Gloss only</button>
    </div>
  );
}

/** Warning text when another particle already has this tag. */
export function sharedTagWarning(engine: ReturnType<typeof useEngine>, tag: string, exceptId?: Id): string | null {
  const others = engine.particlesWithTag(tag, exceptId);
  if (!others.length) return null;
  return `${others.map((l) => engine.form(l.id).label).join(', ')} already ${others.length === 1 ? 'has' : 'have'} this tag.`;
}

export function ParentSelector({ selected, onChange, excludeId }: { selected: Id[]; onChange: (ids: Id[]) => void; excludeId?: Id }) {
  const engine = useEngine();
  const [query, setQuery] = useState('');
  const q = query.toLowerCase();
  const options = useMemo(() => {
    if (!q) return [];
    return engine.doc.lexemes
      .filter((l) => l.id !== excludeId && !selected.includes(l.id))
      .filter((l) => {
        const f = engine.form(l.id);
        return f.roman.toLowerCase().includes(q) || f.phonemic.toLowerCase().includes(q) || engine.glossOf(l).toLowerCase().includes(q);
      })
      .slice(0, 20);
  }, [engine, q, selected, excludeId]);
  return (
    <div className="col" style={{ gap: 6 }}>
      <div style={{ position: 'relative' }}>
        <input type="text" value={query} onChange={(e) => setQuery(e.target.value)} placeholder="Search words to add as parent…" aria-label="Search words to add as parent" />
        {options.length > 0 && (
          <div className="menu" style={{ position: 'absolute', left: 0, right: 0, top: '100%', maxHeight: 220, overflow: 'auto' }}>
            {options.map((l) => (
              <button key={l.id} type="button" className="menu-item" onClick={() => { onChange([...selected, l.id]); setQuery(''); }}>
                {wordOption(engine, l)}
              </button>
            ))}
          </div>
        )}
      </div>
      {selected.length > 0 && (
        <div className="row wrap">
          {selected.map((id) => (
            <Chip key={id} onDelete={() => onChange(selected.filter((x) => x !== id))} title="Remove parent link">
              {engine.lexeme(id) ? wordOption(engine, engine.lexeme(id)!) : `Unknown (#${id})`}
            </Chip>
          ))}
        </div>
      )}
    </div>
  );
}
